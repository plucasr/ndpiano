        let thisFile = URL(fileURLWithPath: #filePath)
        let url = thisFile.deletingLastPathComponent().appendingPathComponent("Fixtures/soft-wave-lead.nsmp4")
        return [UInt8](try Data(contentsOf: url))
    }

    func testIdentify() throws {
        let bytes = try loadFixture()
        let id = identifyNsmp(bytes)
        XCTAssertTrue(id.recognized)
        XCTAssertFalse(id.legacy)
        XCTAssertEqual(id.version, "4.10")
        XCTAssertEqual(id.codec, 4)
        XCTAssertEqual(readNsmpName(bytes), "Soft Wave Lead")
    }

